/// Fixed component dimensions that are not part of the spacing scale.
abstract final class AppSizes {
  /// Minimum height of a button or text field.
  static const double control = 44;

  /// Minimum height of a big button.
  static const double controlBig = 52;

  /// Compact control height used in mini panels.
  static const double controlCompact = 36;

  /// Side of a round icon button.
  static const double iconButton = 44;

  /// Side of a primary round icon button.
  static const double iconButtonPrimary = 48;

  /// Small icon.
  static const double iconSmall = 16;

  /// Regular icon.
  static const double icon = 20;

  /// Large icon.
  static const double iconLarge = 24;

  /// Hero icon of the result dialog.
  static const double iconHero = 56;

  /// Status dot diameter.
  static const double dot = 8;

  /// Height of progress bars and meters.
  static const double bar = 6;

  /// Width of the target marker on a progress bar.
  static const double barMarker = 2;

  /// Height of the target marker on a progress bar.
  static const double barMarkerHeight = 12;

  /// Avatar diameter.
  static const double avatar = 34;

  /// Step number badge diameter.
  static const double stepBadge = 18;

  /// Typing dot diameter.
  static const double typingDot = 6;

  /// Width of the urgency stripe on an order row.
  static const double stripe = 4;

  /// Maximum width of a dialog.
  static const double dialogWidth = 440;

  /// Maximum width of a welcome dialog.
  static const double welcomeWidth = 560;

  /// Maximum width of a result dialog.
  static const double resultWidth = 500;

  /// Unicorn mark in the score bar.
  static const double logoSmall = 44;

  /// Unicorn mark in the welcome hero.
  static const double logoLarge = 120;

  /// Fraction of the available width taken by a chat bubble.
  static const double bubbleWidthFactor = 0.86;
}
